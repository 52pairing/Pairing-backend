package com.pairing.project.application.event;

/**
 * 프로젝트가 취소됐다. 모집 기간 만료(P46)와 클라이언트의 모집 종료에서 발행한다.
 *
 * <p><b>사유를 담지 않는다.</b> 받는 쪽이 할 일이 원인에 따라 달라지지 않아서다. 만료든 수동
 * 종료든 진행 중이던 요청·협상·계약은 똑같이 정리해야 한다. 문구도 "프로젝트가 취소되어" 로
 * 중립으로 쓰면 양쪽에 다 맞는다 — 사유를 넣으면 받는 쪽이 분기해야 하고, 클라이언트 사정을
 * 프리랜서에게 알릴 이유도 없다.
 *
 * <p>{@link ProjectClosedEvent}(정상 종료)와 다르다. 그쪽은 성공보수까지 끝나 계약을 완료로
 * 올리는 신호이고, 이쪽은 진행 중이던 것을 되돌리는 신호다. 재사용하면 취소된 프로젝트의
 * 계약이 완료 처리된다.
 *
 * <p>이 이벤트를 받아 각 도메인이 자기 몫을 정리한다.
 *
 * <pre>
 * 계약   체결된 계약을 중도 파기로            (contract, 같은 담당)
 * 정산   미결제 수수료를 취소                 (settlement, 같은 담당)
 * 매칭   응답하지 않은 요청을 종결             (matching)
 * 협상   진행 중인 협상을 결렬                (negotiation)
 * 알림   프리랜서에게 통지                    (notification)
 * </pre>
 */
public record ProjectCanceledEvent(Long projectId) {
}
