package com.pairing.negotiation.domain.model;

/**
 * 마지노선을 <b>어떤 방식으로 비교하는가</b>. 쟁점 종류마다 다르다.
 *
 * <p>화면이 이걸 알아야 안내 문구를 맞게 쓸 수 있다. 실제로 근무 방식에
 * <b>"재택 이상이어야 합니다"</b> 라고 나가고 있었다 — 선택형에는 크기 비교가 없으므로
 * 성립하지 않는 문장이다(2026-08-12 발견).
 *
 * <p>이 판단은 {@link com.pairing.negotiation.domain.service.NegotiationFloorGuard} 가 실제로
 * 쓰는 규칙과 같아야 한다. 그래서 프론트에 표를 다시 두지 않고 <b>서버가 조건마다 실어 보낸다</b> —
 * 라벨 변환을 서버에 둔 것과 같은 이유다. 쟁점 종류가 늘면 여기만 고치면 된다.
 */
public enum FloorComparison {

    /**
     * 크기 비교. 프리는 하한, 클라는 상한이다.
     * 화면 문구: {@code "480만 원 이상이어야 합니다"} / {@code "~ 이하여야 합니다"}
     */
    RANGE,

    /**
     * 허용값 집합. 크기 관계가 없고 각자 받아들일 수 있는 값을 고른다({@code ANY} 는 전부 허용).
     * 화면 문구: {@code "재택을 허용해야 합니다"}
     */
    CHOICE,

    /**
     * 비교 기준이 없다. 자유 텍스트라 가드가 통과시킨다.
     * 화면은 마지노선 안내를 띄우지 않으면 된다.
     */
    NONE
}
